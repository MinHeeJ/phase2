CREATE TABLE IF NOT EXISTS ai.rcmd_next_rslt (
  rcmd_next_rslt_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME ai.seq_rcmd_next_rslt_id),
  rqst_id BIGINT NOT NULL,
  dev_id BIGINT NOT NULL,
  prj_id BIGINT NULL,
  psn_plan_id BIGINT NULL,
  need_id BIGINT NULL,
  rank_seq INT NOT NULL,
  job_scr DECIMAL(6,2) NOT NULL,
  skl_scr DECIMAL(6,2) NOT NULL,
  cust_scr DECIMAL(6,2) NOT NULL,
  grd_scr DECIMAL(6,2) NOT NULL,
  achv_scr DECIMAL(6,2) NOT NULL,
  exp_scr DECIMAL(6,2) NOT NULL,
  asgn_psbl_scr DECIMAL(6,2) NOT NULL,
  tot_scr DECIMAL(6,2) NOT NULL,
  reason_desc VARCHAR(1000) NULL,
  warnings JSONB NOT NULL DEFAULT '[]'::jsonb,
  decision_cd VARCHAR(10) NOT NULL DEFAULT 'PENDING',
  reject_rsn_desc VARCHAR(500) NULL,
  dcsn_at TIMESTAMP NULL,
  asgn_id BIGINT NULL,
  tmpr_asgn_id BIGINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_rcmd_next_rslt PRIMARY KEY (rcmd_next_rslt_id),
  CONSTRAINT fk_rcmd_next_rslt_rqst FOREIGN KEY (rqst_id) REFERENCES ai.rcmd_rqst (rcmd_rqst_id),
  CONSTRAINT fk_rcmd_next_rslt_dev FOREIGN KEY (dev_id) REFERENCES mst.dev (dev_id),
  CONSTRAINT fk_rcmd_next_rslt_prj FOREIGN KEY (prj_id) REFERENCES prj.prj (prj_id),
  CONSTRAINT fk_rcmd_next_rslt_plan FOREIGN KEY (psn_plan_id) REFERENCES prj.psn_plan (psn_plan_id),
  CONSTRAINT fk_rcmd_next_rslt_need FOREIGN KEY (need_id) REFERENCES bsn.oppt_need (need_id),
  CONSTRAINT fk_rcmd_next_rslt_asgn FOREIGN KEY (asgn_id) REFERENCES asgn.asgn (asgn_id),
  CONSTRAINT fk_rcmd_next_rslt_tmpr FOREIGN KEY (tmpr_asgn_id) REFERENCES asgn.tmpr_asgn (tmpr_asgn_id),
  CONSTRAINT ck_rcmd_next_rslt_slot_vld CHECK (
    (psn_plan_id IS NOT NULL AND prj_id IS NOT NULL AND need_id IS NULL) OR
    (psn_plan_id IS NULL AND prj_id IS NULL AND need_id IS NOT NULL)),
  CONSTRAINT ck_rcmd_next_rslt_rank_rng CHECK (rank_seq BETWEEN 1 AND 10),
  CONSTRAINT uk_rcmd_next_rslt_rank UNIQUE (rqst_id, rank_seq),
  CONSTRAINT ck_rcmd_next_rslt_scores_rng CHECK (
    job_scr BETWEEN 0 AND 25 AND skl_scr BETWEEN 0 AND 20 AND cust_scr BETWEEN 0 AND 15 AND
    grd_scr BETWEEN 0 AND 10 AND achv_scr BETWEEN 0 AND 10 AND exp_scr BETWEEN 0 AND 10 AND
    asgn_psbl_scr BETWEEN 0 AND 10 AND tot_scr BETWEEN 0 AND 100 AND
    tot_scr = job_scr + skl_scr + cust_scr + grd_scr + achv_scr + exp_scr + asgn_psbl_scr),
  CONSTRAINT ck_rcmd_next_rslt_decision_vld CHECK (decision_cd IN ('PENDING','ADOPT','REJECT')),
  CONSTRAINT ck_rcmd_next_rslt_reject_vld CHECK (decision_cd <> 'REJECT' OR
    (reject_rsn_desc IS NOT NULL AND length(btrim(reject_rsn_desc)) BETWEEN 1 AND 500)),
  CONSTRAINT ck_rcmd_next_rslt_warnings_vld CHECK (jsonb_typeof(warnings) = 'array')
);
COMMENT ON TABLE ai.rcmd_next_rslt IS '개발자 한 명의 다음 자리 추천 실행 결과. 점수와 자리 원천은 실행 당시 보존하고 결정 및 사용자 저장 성공 링크만 후속 변경한다.';
COMMENT ON COLUMN ai.rcmd_next_rslt.psn_plan_id IS '프로젝트의 원래 월별 직무·등급 인원계획 자리 식별자. prj_id만으로 자리를 합치지 않는다.';
COMMENT ON COLUMN ai.rcmd_next_rslt.prj_id IS '프로젝트 자리의 설명용 부모. 실제 자리 정체성은 psn_plan_id이다.';
COMMENT ON COLUMN ai.rcmd_next_rslt.tot_scr IS '추천 서비스가 실행 시 일곱 점수의 둘째 자리 HALF_UP 결과를 합산해 저장하며 재조회 시 갱신하지 않는다.';
CREATE UNIQUE INDEX IF NOT EXISTS uk_rcmd_next_rslt_plan ON ai.rcmd_next_rslt (rqst_id, psn_plan_id) WHERE psn_plan_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_rcmd_next_rslt_need ON ai.rcmd_next_rslt (rqst_id, need_id) WHERE need_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_rcmd_next_rslt_dev ON ai.rcmd_next_rslt (dev_id, decision_cd);

