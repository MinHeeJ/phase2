-- Preserve legacy business history: conflicting rows must be reviewed before migration.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM fin.entry WHERE copy_entry_id IS NOT NULL
      GROUP BY entry_ym, copy_entry_id HAVING count(*) > 1) THEN
    RAISE EXCEPTION 'Duplicate finance entry copy history; review entry_ym/copy_entry_id before migration';
  END IF;
  IF EXISTS (SELECT 1 FROM fin.pay WHERE cry_pay_id IS NULL AND src_rec_id IS NOT NULL
      AND pay_src_cd <> 'MANUAL'
      GROUP BY pay_src_cd, src_rec_id, pay_se_cd, pay_ym HAVING count(*) > 1) THEN
    RAISE EXCEPTION 'Duplicate finance payment sources; review source/category/month before migration';
  END IF;
  IF EXISTS (SELECT 1 FROM fin.pay WHERE cry_pay_id IS NOT NULL AND pay_stts_cd <> 'CANCEL'
      GROUP BY cry_pay_id HAVING count(*) > 1) THEN
    RAISE EXCEPTION 'Duplicate active finance carry children; review cry_pay_id before migration';
  END IF;
  IF (SELECT count(*) FROM fin.cash_bal WHERE init_yn = 'Y') > 1 THEN
    RAISE EXCEPTION 'Multiple finance opening balances; review initial balances before migration';
  END IF;
END
$$;

