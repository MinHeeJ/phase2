CREATE TABLE IF NOT EXISTS fin.pay_execution (
  pay_execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME fin.seq_pay_execution_id),
  pay_id BIGINT NOT NULL,
  pay_dt DATE NOT NULL,
  pay_amt BIGINT NOT NULL,
  reversal_of_id BIGINT NULL,
  rsn_desc VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by BIGINT NULL,
  CONSTRAINT pk_pay_execution PRIMARY KEY (pay_execution_id),
  CONSTRAINT fk_pay_execution_pay FOREIGN KEY (pay_id) REFERENCES fin.pay (pay_id),
  CONSTRAINT fk_pay_execution_reversal FOREIGN KEY (reversal_of_id) REFERENCES fin.pay_execution (pay_execution_id),
  CONSTRAINT ck_pay_execution_amount_vld CHECK (
    (reversal_of_id IS NULL AND pay_amt >= 0) OR (reversal_of_id IS NOT NULL AND pay_amt <= 0)),
  CONSTRAINT ck_pay_execution_reversal_reason CHECK (
    reversal_of_id IS NULL OR (rsn_desc IS NOT NULL AND length(btrim(rsn_desc)) > 0))
);
COMMENT ON TABLE fin.pay_execution IS '지급 건별 실제 지급과 취소 반대 실행의 추가 전용 이력. 계획 금액을 보존하고 실제 지급일별 현금 지출을 집계한다.';
COMMENT ON COLUMN fin.pay_execution.pay_dt IS '실제 지급일. 취소 실행은 취소 대상 실적에 대응하는 날짜로 기록한다.';
COMMENT ON COLUMN fin.pay_execution.pay_amt IS '실제 지급 원 금액. 취소 실행은 원 실행과 같은 크기의 음수로 기록한다.';
COMMENT ON COLUMN fin.pay_execution.created_by IS 'sys.user_info.user_id 참조 의도 (FK 미선언)';
CREATE UNIQUE INDEX IF NOT EXISTS uk_pay_execution_reversal
  ON fin.pay_execution (reversal_of_id) WHERE reversal_of_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_pay_execution_pay_id_pay_dt ON fin.pay_execution (pay_id, pay_dt);
CREATE INDEX IF NOT EXISTS ix_pay_execution_pay_dt ON fin.pay_execution (pay_dt);

INSERT INTO fin.pay_execution (pay_id, pay_dt, pay_amt, created_at, created_by)
  SELECT pay_id, pay_dt, pay_amt, created_at, created_by FROM fin.pay
  WHERE pay_stts_cd = 'PAID' AND pay_dt IS NOT NULL;

CREATE OR REPLACE FUNCTION fin.fn_preserve_pay_execution() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Payment executions are append-only; record a reversal instead' USING ERRCODE = '23514';
END
$$;
CREATE TRIGGER trg_pay_execution_immutable BEFORE UPDATE OR DELETE ON fin.pay_execution
  FOR EACH ROW EXECUTE FUNCTION fin.fn_preserve_pay_execution();

CREATE OR REPLACE FUNCTION fin.fn_validate_pay_reversal() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  original fin.pay_execution%ROWTYPE;
BEGIN
  IF NEW.reversal_of_id IS NOT NULL THEN
    SELECT * INTO original FROM fin.pay_execution WHERE pay_execution_id = NEW.reversal_of_id;
    IF NOT FOUND OR original.reversal_of_id IS NOT NULL OR original.pay_id <> NEW.pay_id
        OR original.pay_amt::numeric + NEW.pay_amt::numeric <> 0 THEN
      RAISE EXCEPTION 'A reversal must negate one original execution of the same payment' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER trg_pay_execution_reversal BEFORE INSERT ON fin.pay_execution
  FOR EACH ROW EXECUTE FUNCTION fin.fn_validate_pay_reversal();
