CREATE TABLE IF NOT EXISTS sys.login_session (
  session_id_hash VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL REFERENCES sys.user_info(user_id),
  created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  last_activity_at TIMESTAMP NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  revoked_at TIMESTAMP,
  csrf_token_hash VARCHAR(64),
  password_change_required_yn CHAR(1) NOT NULL DEFAULT 'N',
  CONSTRAINT pk_login_session PRIMARY KEY (session_id_hash),
  CONSTRAINT ck_login_session_hash_fmt CHECK (session_id_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT ck_login_session_csrf_fmt CHECK (csrf_token_hash IS NULL OR csrf_token_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT ck_login_session_change_vld CHECK (password_change_required_yn IN ('Y','N')),
  CONSTRAINT ck_login_session_activity_prd CHECK (last_activity_at >= created_at AND expires_at > last_activity_at)
);
COMMENT ON TABLE sys.login_session IS '로그인 완료 후 발급한 공유 서버 세션의 해시와 유휴 만료·폐기 상태. 두 노드가 동일 PostgreSQL 상태로 접근을 판정한다.';
COMMENT ON COLUMN sys.login_session.last_activity_at IS '세션 서비스가 검증한 실제 사용자 활동 시 서버 서울 시각으로 갱신하며 폴링은 갱신하지 않는다.';
COMMENT ON COLUMN sys.login_session.expires_at IS '세션 서비스가 생성 및 실제 활동 반영 시 last_activity_at + 30분으로 갱신한다. 물리 정리 지연과 무관하게 요청 시 동기 검사한다.';
COMMENT ON COLUMN sys.login_session.csrf_token_hash IS '쓰기 요청 CSRF 증명의 해시만 보관한다.';
CREATE INDEX IF NOT EXISTS ix_login_session_user_revoked ON sys.login_session(user_id, revoked_at);
CREATE INDEX IF NOT EXISTS ix_login_session_expires ON sys.login_session(expires_at);

