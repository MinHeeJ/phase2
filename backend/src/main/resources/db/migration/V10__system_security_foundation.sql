-- Session/token expiration is checked synchronously; cleanup must not gate rejection.
-- Audit retention is at least three years; this migration never deletes history.
-- SMTP can deliver before a process crashes prior to acknowledgement: delivery is not exactly-once.

CREATE OR REPLACE FUNCTION sys.fn_menu_default_permissions() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO sys.role_menu_auth(role_id,menu_id,inq_auth_yn,reg_auth_yn,mdfcn_auth_yn,del_auth_yn,upld_auth_yn,dwnld_auth_yn,cnfrm_auth_yn)
  SELECT role_id,NEW.menu_id,'N','N','N','N','N','N','N' FROM sys.role
  ON CONFLICT(role_id,menu_id) DO NOTHING;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_menu_default_permissions AFTER INSERT ON sys.menu
FOR EACH ROW EXECUTE FUNCTION sys.fn_menu_default_permissions();
