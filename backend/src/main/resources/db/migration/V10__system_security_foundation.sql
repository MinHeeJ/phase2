CREATE TABLE IF NOT EXISTS sys.ntf_event_key (
  event_key_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sys.seq_ntf_event_key_id),
  event_type_cd VARCHAR(30) NOT NULL,
  business_object_id TEXT NOT NULL,
  threshold_or_date TEXT NOT NULL,
  bsn_part_id BIGINT REFERENCES mst.bsn_part(bsn_part_id),
  job_cd VARCHAR(30),
  base_ym CHAR(7),
  occurrence_seq BIGINT NOT NULL DEFAULT 1,
  opened_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  resolved_at TIMESTAMP,
  shortage_mm_qty NUMERIC,
  CONSTRAINT pk_ntf_event_key PRIMARY KEY (event_key_id),
  CONSTRAINT uk_ntf_event_occurrence UNIQUE(event_type_cd, business_object_id, threshold_or_date, occurrence_seq),
  CONSTRAINT ck_ntf_event_occurrence_rng CHECK (occurrence_seq > 0),
  CONSTRAINT ck_ntf_event_month_fmt CHECK (base_ym IS NULL OR base_ym ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_ntf_event_resolved_prd CHECK (resolved_at IS NULL OR resolved_at >= opened_at),
  CONSTRAINT ck_ntf_event_shortage_vld CHECK (event_type_cd <> 'STAFF_SHORTAGE' OR (bsn_part_id IS NOT NULL AND job_cd IS NOT NULL AND base_ym IS NOT NULL AND shortage_mm_qty IS NOT NULL))
);
COMMENT ON TABLE sys.ntf_event_key IS '수신자와 독립인 업무 사건 발생 차수와 해소 이력. 부족 사건은 파트·직무·부족예상월별로 보존한다.';
COMMENT ON COLUMN sys.ntf_event_key.event_type_cd IS 'DUNNING:미수|RISK_PROJECT:프로젝트위험|WITHDRAW:철수|CASH_SHORT:현금부족|LOW_MARGIN:저수익|QUOTE_APPROVAL:견적승인|UPLOAD:업로드|AI_RECOMMEND:추천|MONTH_CLOSE_MISSING:월마감누락|STAFF_SHORTAGE:인력부족';
COMMENT ON COLUMN sys.ntf_event_key.business_object_id IS '업무별 원천 식별자 참조 의도 (FK 미선언). STAFF_SHORTAGE는 수신자 없는 파트·직무 정규키이다.';
COMMENT ON COLUMN sys.ntf_event_key.job_cd IS 'cmn.cd_dtl JOB 직무 코드 참조 의도 (FK 미선언)';
COMMENT ON COLUMN sys.ntf_event_key.shortage_mm_qty IS '알림 사건 서비스가 기존 인력 계산 결과로 발생·재조회 시 갱신한다. 월별 >0.40 발생, <=0.40 해소.';
CREATE UNIQUE INDEX IF NOT EXISTS uk_ntf_event_unresolved ON sys.ntf_event_key(event_type_cd, business_object_id, threshold_or_date) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_ntf_event_part_month ON sys.ntf_event_key(bsn_part_id, base_ym);
