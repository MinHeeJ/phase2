CREATE TABLE IF NOT EXISTS sys.mail_outbox (
  mail_outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sys.seq_mail_outbox_id),
  ntf_id BIGINT REFERENCES sys.ntf(ntf_id),
  auth_tkn_id BIGINT REFERENCES sys.auth_tkn(tkn_id),
  recipient_user_id BIGINT NOT NULL REFERENCES sys.user_info(user_id),
  mail_ty_cd VARCHAR(20) NOT NULL,
  send_stts_cd VARCHAR(10) NOT NULL DEFAULT 'PENDING',
  retry_cnt INTEGER NOT NULL DEFAULT 0,
  next_retry_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  claimed_until_at TIMESTAMP,
  claim_id VARCHAR(64),
  sent_at TIMESTAMP,
  last_error_cd VARCHAR(40),
  created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'),
  CONSTRAINT pk_mail_outbox PRIMARY KEY (mail_outbox_id),
  CONSTRAINT ck_mail_outbox_type_vld CHECK (mail_ty_cd IN ('MFA','RESET','NOTIFICATION')),
  CONSTRAINT ck_mail_outbox_status_vld CHECK (send_stts_cd IN ('PENDING','SENDING','SENT','FAILED')),
  CONSTRAINT ck_mail_outbox_retry_rng CHECK (retry_cnt BETWEEN 0 AND 3),
  CONSTRAINT ck_mail_outbox_reference_vld CHECK (
    (mail_ty_cd='NOTIFICATION' AND ntf_id IS NOT NULL AND auth_tkn_id IS NULL) OR
    (mail_ty_cd IN ('MFA','RESET') AND auth_tkn_id IS NOT NULL AND ntf_id IS NULL)),
  CONSTRAINT ck_mail_outbox_error_fmt CHECK (last_error_cd IS NULL OR last_error_cd ~ '^[A-Z][A-Z0-9_]{0,39}$'),
  CONSTRAINT ck_mail_outbox_claim_fmt CHECK (claim_id IS NULL OR claim_id ~ '^[a-zA-Z0-9-]{1,64}$')
);
COMMENT ON TABLE sys.mail_outbox IS '업무 트랜잭션과 함께 저장하는 메일 발송 의도와 DB claim lease. 주소·본문·OTP·RESET URL은 저장하지 않으며 SMTP 성공 후만 발송 완료한다.';
COMMENT ON COLUMN sys.mail_outbox.claim_id IS '메일 dispatcher의 서버 생성 claim 식별자. 이전 lease 작업자의 늦은 성공 응답을 거절한다.';
COMMENT ON COLUMN sys.mail_outbox.retry_cnt IS '메일 dispatcher가 최초 시도 이후 재시도 때 증가시킨다. 최대 세 번이며 지연은 60/120/240초이다.';
COMMENT ON COLUMN sys.mail_outbox.claimed_until_at IS '메일 dispatcher가 DB 잠금 아래 claim 시 현재 시각 + 60초로 갱신한다. 만료 lease는 회수한다.';
COMMENT ON COLUMN sys.mail_outbox.last_error_cd IS '정제된 오류 코드만 저장하며 SMTP 예외 메시지·주소·인증 증명은 기록하지 않는다.';
CREATE UNIQUE INDEX IF NOT EXISTS uk_mail_outbox_notification ON sys.mail_outbox(ntf_id) WHERE ntf_id IS NOT NULL;
