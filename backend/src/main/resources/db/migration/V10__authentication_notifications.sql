COMMENT ON COLUMN sys.auth_tkn.issued_at IS '인증 메일 dispatcher가 현재 세대 증명 발급 시 서버 서울 시각으로 기록; 과거 NULL은 보존';
COMMENT ON COLUMN sys.auth_tkn.otp_fail_cnt IS '인증 서비스가 계정 잠금 아래 실패 시 누적; 재전송으로 초기화하지 않음';
COMMENT ON COLUMN sys.auth_tkn.last_sent_at IS '메일 dispatcher가 SMTP 성공 시 갱신';
ALTER TABLE sys.user_info ADD COLUMN IF NOT EXISTS otp_fail_cnt INTEGER NOT NULL DEFAULT 0;
ALTER TABLE sys.user_info ADD CONSTRAINT ck_user_info_otp_fail_cnt CHECK (otp_fail_cnt BETWEEN 0 AND 5);
COMMENT ON COLUMN sys.user_info.otp_fail_cnt IS '인증 서비스가 계정 행 잠금 아래 누적; 완전 로그인 또는 정상 RESET에서만 초기화';
CREATE INDEX IF NOT EXISTS ix_auth_tkn_user_type ON sys.auth_tkn(user_id, tkn_ty_cd, created_at);
CREATE INDEX IF NOT EXISTS ix_auth_tkn_expir_at ON sys.auth_tkn(expir_at);

CREATE TABLE IF NOT EXISTS sys.login_session (
    session_id_hash VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES sys.user_info(user_id),
    created_at TIMESTAMP NOT NULL,
    last_activity_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    CONSTRAINT pk_login_session PRIMARY KEY(session_id_hash),
    CONSTRAINT ck_login_session_hash CHECK (session_id_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_login_session_time CHECK (last_activity_at >= created_at AND expires_at > last_activity_at)
);
COMMENT ON TABLE sys.login_session IS '완전 인증된 서버 세션의 해시와 유효기간을 공유한다. 매 요청 만료·회수를 검사하고 물리 정리는 별도로 수행한다.';
COMMENT ON COLUMN sys.login_session.last_activity_at IS '인증 서비스의 검증된 KEY/CLICK/NAVIGATION 활동만 서버 서울 시각으로 갱신; 자동 폴링 제외';
COMMENT ON COLUMN sys.login_session.expires_at IS '인증 서비스가 세션 생성 및 검증 활동 시 last_activity_at+30분으로 갱신';
CREATE INDEX IF NOT EXISTS ix_login_session_user ON sys.login_session(user_id, revoked_at);
CREATE INDEX IF NOT EXISTS ix_login_session_expiry ON sys.login_session(expires_at);

CREATE TABLE IF NOT EXISTS sys.ntf_event_key (
    event_key_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sys.seq_ntf_event_key_id),
    event_type_cd VARCHAR(30) NOT NULL,
    business_object_id VARCHAR(200) NOT NULL,
    threshold_or_date VARCHAR(100) NOT NULL,
    bsn_part_id BIGINT REFERENCES mst.bsn_part(bsn_part_id),
    job_cd VARCHAR(30),
    base_ym CHAR(7),
    occurrence_seq BIGINT NOT NULL DEFAULT 1,
    opened_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,
    shortage_mm_qty NUMERIC(18,4),
    CONSTRAINT pk_ntf_event_key PRIMARY KEY(event_key_id),
    CONSTRAINT uk_ntf_event_occurrence UNIQUE(event_type_cd, business_object_id, threshold_or_date, occurrence_seq),
    CONSTRAINT ck_ntf_event_occurrence CHECK (occurrence_seq > 0),
    CONSTRAINT ck_ntf_event_type CHECK (event_type_cd IN ('DUNNING','RISK_PROJECT','WITHDRAW','CASH_SHORT','LOW_MARGIN','QUOTE_APPROVAL','UPLOAD','AI_RECOMMEND','MONTH_CLOSE_MISSING','STAFF_SHORTAGE')),
    CONSTRAINT ck_ntf_event_period CHECK (base_ym IS NULL OR base_ym ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    CONSTRAINT ck_ntf_event_resolution CHECK (resolved_at IS NULL OR resolved_at >= opened_at)
);
COMMENT ON TABLE sys.ntf_event_key IS '수신자와 독립된 업무 사건 발생 이력이다. 같은 미해결 사건은 유지하고 해소 후 재발생은 새 발생 순번으로 저장한다.';
COMMENT ON COLUMN sys.ntf_event_key.business_object_id IS '유형별 업무 원천 식별자 참조 의도 (FK 미선언); 인력부족은 파트와 직무의 손실 없는 정규화키';
COMMENT ON COLUMN sys.ntf_event_key.shortage_mm_qty IS '알림 사건 서비스가 기존 부족 판정 조회 결과로 재평가 시 갱신; 원천 산식은 변경하지 않음';
CREATE UNIQUE INDEX IF NOT EXISTS uk_ntf_event_open ON sys.ntf_event_key(event_type_cd, business_object_id, threshold_or_date) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_ntf_event_opened ON sys.ntf_event_key(opened_at);
ALTER TABLE sys.ntf ADD COLUMN IF NOT EXISTS event_key_id BIGINT REFERENCES sys.ntf_event_key(event_key_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_ntf_event_recipient ON sys.ntf(event_key_id, user_id) WHERE event_key_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_ntf_recipient_time ON sys.ntf(user_id, created_at DESC, ntf_id DESC);
CREATE INDEX IF NOT EXISTS ix_ntf_recipient_unread ON sys.ntf(user_id, created_at DESC) WHERE read_yn = 'N';

CREATE TABLE IF NOT EXISTS sys.mail_outbox (
    mail_outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME sys.seq_mail_outbox_id),
    ntf_id BIGINT REFERENCES sys.ntf(ntf_id),
    auth_tkn_id BIGINT REFERENCES sys.auth_tkn(tkn_id),
    recipient_user_id BIGINT NOT NULL REFERENCES sys.user_info(user_id),
    mail_ty_cd VARCHAR(20) NOT NULL,
    send_stts_cd VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    retry_cnt INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP NOT NULL,
    claimed_until_at TIMESTAMP,
    sent_at TIMESTAMP,
    last_error_cd VARCHAR(40),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_mail_outbox PRIMARY KEY(mail_outbox_id),
    CONSTRAINT ck_mail_outbox_reference CHECK (
        (mail_ty_cd = 'NOTIFICATION' AND ntf_id IS NOT NULL AND auth_tkn_id IS NULL)
        OR (mail_ty_cd IN ('MFA','RESET') AND auth_tkn_id IS NOT NULL AND ntf_id IS NULL)),
    CONSTRAINT ck_mail_outbox_status CHECK (send_stts_cd IN ('PENDING','SENDING','SENT','FAILED')),
    CONSTRAINT ck_mail_outbox_retry CHECK (retry_cnt BETWEEN 0 AND 3),
    CONSTRAINT ck_mail_outbox_sent CHECK ((send_stts_cd = 'SENT') = (sent_at IS NOT NULL)),
    CONSTRAINT ck_mail_outbox_error CHECK (last_error_cd IS NULL OR last_error_cd ~ '^[A-Z][A-Z0-9_]{0,39}$')
);
COMMENT ON TABLE sys.mail_outbox IS '업무 및 인증 메일의 참조와 전송 상태만 저장한다. 주소·메일 본문·OTP·RESET 원문 또는 복호화 가능한 증명은 저장하지 않는다.';
COMMENT ON COLUMN sys.mail_outbox.send_stts_cd IS 'PENDING:발송대기|SENDING:발송중|SENT:발송완료|FAILED:발송실패';
COMMENT ON COLUMN sys.mail_outbox.retry_cnt IS '메일 dispatcher가 실패 후 재예약 시 증가; 최초 시도와 별도로 최대 3회';
CREATE UNIQUE INDEX IF NOT EXISTS uk_mail_outbox_ntf ON sys.mail_outbox(ntf_id) WHERE ntf_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uk_mail_outbox_auth ON sys.mail_outbox(auth_tkn_id) WHERE auth_tkn_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_mail_outbox_retry ON sys.mail_outbox(send_stts_cd, next_retry_at);
CREATE INDEX IF NOT EXISTS ix_mail_outbox_claim ON sys.mail_outbox(claimed_until_at) WHERE send_stts_cd = 'SENDING';

