    ADD CONSTRAINT ck_auth_tkn_issuance CHECK (
        (issuance_stts_cd = 'PENDING' AND tkn_hash IS NULL AND expir_at IS NULL AND issued_at IS NULL)
        OR (issuance_stts_cd = 'ISSUED' AND tkn_hash IS NOT NULL AND expir_at IS NOT NULL)),
    ADD CONSTRAINT ck_auth_tkn_otp_fail_cnt CHECK (otp_fail_cnt BETWEEN 0 AND 5);
