    ALTER COLUMN expir_at DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS issued_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS otp_fail_cnt INTEGER NOT NULL DEFAULT 0,
