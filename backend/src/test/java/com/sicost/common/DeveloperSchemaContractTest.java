package com.sicost.common;

import static org.assertj.core.api.Assertions.*;

import java.nio.charset.StandardCharsets;
import java.util.Map;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;

class DeveloperSchemaContractTest {
    private String read(String resource) throws Exception {
        try (var input = new ClassPathResource(resource).getInputStream()) {
            return new String(input.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    private String table(String name) throws Exception {
        String schema = read("db/migration/V1__schema.sql");
        var match = Pattern.compile("CREATE TABLE IF NOT EXISTS " + Pattern.quote(name) + " \\((.*?)\\n\\);", Pattern.DOTALL).matcher(schema);
        assertThat(match.find()).as("existing V1 table %s", name).isTrue();
        return match.group(1).replaceAll("\\s+", " ").trim();
    }

    @Test void gradeAndUseAreExistingDeveloperColumnsNotNewTables() throws Exception {
        String developer = table("mst.dev");
        assertThat(developer).contains("grd_cd VARCHAR(30) NULL", "use_yn CHAR(1) NOT NULL DEFAULT 'Y'");
        assertThat(read("db/migration/V1__schema.sql"))
            .doesNotContain("CREATE TABLE IF NOT EXISTS grd_cd", "CREATE TABLE IF NOT EXISTS use_yn");
    }

    @Test void managementNumberRequiresFinalValueBeforeInsertAndIsUniqueNotTheName() throws Exception {
        assertThat(table("mst.dev")).contains(
            "dev_id BIGINT GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME mst.seq_dev_id)",
            "mng_no VARCHAR(20) NOT NULL", "CONSTRAINT uk_dev_mng_no UNIQUE (mng_no)")
            .doesNotContain("UNIQUE (dev_nm)");
    }

    @Test void developerApiStorageFieldsAlreadyExistInV1() throws Exception {
        String developer = table("mst.dev");
        for (String field : new String[] {"dev_id", "mng_no", "dev_nm", "tel_no", "email_addr", "vndr_ptnr_id",
            "pstn_cd", "emp_se_cd", "duty_se_cd", "grd_cd", "main_job_cd", "bsn_part_id", "dflt_untprc_amt",
            "hire_dt", "rsgn_dt", "rmrk_desc", "use_yn", "upld_id", "created_at", "created_by", "updated_at", "updated_by"}) {
            assertThat(developer).as(field).containsPattern("\\b" + field + "\\s");
        }
    }

    @Test void replaceableChildrenRetainCompositeIdentitiesAndParentForeignKeys() throws Exception {
        assertThat(table("mst.dev_sub_job")).contains("PRIMARY KEY (dev_id, job_cd)");
        assertThat(table("mst.dev_skl")).contains("PRIMARY KEY (dev_id, skl_cd)");
        String schema = read("db/migration/V1__schema.sql");
        for (String child : new String[] {"dev_sub_job", "dev_skl", "dev_work_stts_hist"}) {
            assertThat(schema).containsPattern("ALTER TABLE mst\\." + child
                + " ADD CONSTRAINT \\w+ FOREIGN KEY \\(dev_id\\) REFERENCES mst\\.dev \\(dev_id\\)");
        }
    }

    @Test void workStatusSupportsOpenEndedPeriodsAndSeparateAuditIdentity() throws Exception {
        assertThat(table("mst.dev_work_stts_hist")).contains(
            "PRIMARY KEY (work_stts_hist_id)", "dev_id BIGINT NOT NULL", "bgn_dt DATE NOT NULL",
            "end_dt DATE NULL", "paid_yn CHAR(1) NOT NULL DEFAULT 'N'",
            "CHECK (end_dt IS NULL OR end_dt >= bgn_dt)");
        assertThat(table("sys.data_chg_hist")).contains("obj_rec_id VARCHAR(50) NOT NULL",
            "bfr_val VARCHAR(4000) NULL", "aft_val VARCHAR(4000) NULL", "rsn_desc VARCHAR(500) NULL");
    }

    @Test void salaryHasOneRowPerPersonAndMonthAndDatabaseOwnedCalculatedMoney() throws Exception {
        assertThat(table("cst.mth_cst")).contains(
            "UNIQUE (dev_id, cst_ym)",
            "indv_lbr_cst_amt BIGINT GENERATED ALWAYS AS ( CASE WHEN emp_se_cd IN ('FT','CT') THEN slry_amt + alwnc_amt + sins_cmpny_amt + rtrpay_acml_amt ELSE slry_amt END) STORED",
            "real_pay_amt BIGINT GENERATED ALWAYS AS ( CASE WHEN emp_se_cd = 'OS' THEN slry_amt + vat_amt ELSE slry_amt + alwnc_amt - sins_emp_amt - whtax_amt - ern_tax_amt END) STORED");
    }

    @Test void salarySnapshotAndExpenseProvenanceNeedNoAdditionalColumns() throws Exception {
        assertThat(table("cst.mth_cst")).contains("emp_se_cd VARCHAR(10) NOT NULL", "duty_se_cd VARCHAR(10)",
            "pstn_cd VARCHAR(30) NULL", "bsn_part_id BIGINT NULL", "upld_id BIGINT NULL", "excel_diff_desc VARCHAR(500) NULL");
        assertThat(table("cst.drct_expns")).contains("dev_id BIGINT NULL", "prj_id BIGINT NULL",
            "expns_ym CHAR(7) NOT NULL", "expns_item_cd VARCHAR(30) NOT NULL", "upld_id BIGINT NULL");
        assertThat(table("sys.upld")).contains("form_cd VARCHAR(10) NOT NULL", "obj_ym CHAR(7) NULL",
            "ovwr_yn CHAR(1) NOT NULL DEFAULT 'N'");
    }

    @Test void existingAssignmentAndMonthlyMmFieldsAreAvailableForReadOnlyQueries() throws Exception {
        assertThat(table("asgn.asgn")).contains("dev_id BIGINT NOT NULL", "prj_id BIGINT NOT NULL",
            "asgn_stts_cd VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'", "bgn_dt DATE NOT NULL", "end_dt DATE NOT NULL");
        assertThat(table("asgn.asgn_mth")).contains("work_ym CHAR(7) NOT NULL", "mm_qty DECIMAL(5,2) NOT NULL");
        assertThat(table("prj.prj")).contains("prj_stts_cd VARCHAR(10) NOT NULL DEFAULT 'PLAN'");
    }

    @Test void monthCloseSeedKeepsSeptemberClosedAndOctoberOpenWithoutBusinessSeeds() throws Exception {
        String seed = read("db/migration/V2__seed_month_close.sql");
        assertThat(seed).contains("('2026-09', 'CLOSED', TIMESTAMP '2026-10-05 00:00:00')",
            "VALUES ('2026-10', 'OPEN')");
        for (String migration : new String[] {"V2__seed_month_close.sql", "V3__seed_bank.sql"}) {
            assertThat(read("db/migration/" + migration)).doesNotContain("INSERT INTO mst.dev", "INSERT INTO cst.mth_cst", "INSERT INTO asgn.asgn");
        }
    }

    @Test void reusedCodeAndParameterOperationsRemainPublicInTheDurableContract() throws Exception {
        Map<String, Object> contract;
        try (var input = new ClassPathResource("contracts/openapi.yaml").getInputStream()) {
            contract = new org.yaml.snakeyaml.Yaml().load(input);
        }
        Map<?, ?> paths = (Map<?, ?>) contract.get("paths");
        for (String path : new String[] {"/api/codes/{group}", "/api/params/{key}", "/api/month-close"}) {
            assertThat(paths.containsKey(path)).as(path).isTrue();
            Map<?, ?> operations = (Map<?, ?>) paths.get(path);
            for (String method : new String[] {"get", "post"}) {
                if (operations.get(method) instanceof Map<?, ?> operation) {
                    assertThat(operation.get("security")).isIn(null, java.util.List.of());
                    assertThat(operation.containsKey("x-roles")).isFalse();
                }
            }
        }
    }
}
